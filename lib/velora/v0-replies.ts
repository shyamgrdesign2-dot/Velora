    "Endocrinology": "Endo",
    "Diabetology": "Diab",
    "Neurology": "Neuro",
    "Neurosurgery": "Neuro-Sx",
    "Rheumatology": "Rheum",
    "Pain Specialist": "Pain",
    "Internal Medicine": "IntMed",
    "Orthopaedics": "Ortho",
    "ENT": "ENT",
