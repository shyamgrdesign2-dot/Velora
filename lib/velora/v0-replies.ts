/** Top-N sub-intent suggestions for a parent intent — rendered as inline
 *  canned pills directly under the card the doctor is reading. */
function subSuggestionsFor(parent: VeloraParentIntent, n: number = 2) {
  return getVeloraFollowUps(parent)
    .slice(0, n)
    .map((f) => ({ label: f.quickLabel, message: f.question }))
}

/**
 * briefTrendSuggestions — chips shown under the Cross-consultation brief
 * reply. Returns the top-N per-patient trend questions from the trends
 * registry, e.g. "HbA1c trend", "BP trend", "eGFR trend" — chosen
 * because they are clinically actionable for *this* patient's problem
 * list (see `v0-trends.ts` and `docs/velora-v0-recent-trends.md` for
 * the rule-table that drives the selection).
 *
 * Each chip when tapped fires the canonical trend question, which the
 * reply pipeline matches against the patient's trends registry and
 * either renders the canned reply or trips the guardrail.
 */
function briefTrendSuggestions(
  data: VeloraV0MdtBriefData,
  n: number = 4,
): Array<{ label: string; message: string }> {
  const profile = resolvePatientTrends(data.patientName)
  return profile.trends.slice(0, n).map((t) => ({
    label: `${t.quickLabel} trend`,
    message: t.question,
  }))
}

/**
 * buildBriefPreamble — rule-based, fully data-driven sentence that
 * introduces the Cross-consultation brief card in the chat.
 *
 * NOT generated by AI. The structure is a fixed template; only the
 * numbers / names / dates are pulled from `VeloraV0MdtBriefData`. Drops
 * the old "OMOP record" / "verbatim" phrasing and frames the line as a
 * plain-English summary the doctor can read before opening the card.
 *
 * Template
 *   "Here's the cross-consultation brief for {patient}. {encounters}
 *    encounters across {N} specialties — {specialty list} — over
 *    {months} months ({range}), seen by {N} doctors."
 *
 * Each clause is dropped gracefully when its data isn't available.
 * `**bold**` segments are honoured by the ChatBubble's markdown
 * renderer so the key numbers + diagnosis still pop visually.
 */
function buildBriefPreamble(data: VeloraV0MdtBriefData): string {
  const months = Math.max(1, Math.round((data.windowDays ?? 0) / 30))
  // Total encounter count across every specialty.
  const encounters = data.specialties.reduce((sum, rec) => {
    if (typeof rec.consultationCount === "number") return sum + rec.consultationCount
    return sum + (rec.consultations?.length ?? 0)
  }, 0)
  const specialtyCount = data.specialties.map((r) => r.source.specialty).filter(Boolean).length
  // Unique doctor names across the whole window.
  const doctorSet = new Set<string>()
  for (const rec of data.specialties) {
    for (const c of rec.consultations ?? []) {
      const n = c.doctor?.trim()
      if (n) doctorSet.add(n)
    }
  }
  const doctorCount = doctorSet.size
  // Window range — earliest start, latest end across every specialty.
  const parseDate = (s: string): number | null => {
    const t = Date.parse(s)
    return Number.isNaN(t) ? null : t
  }
  let minStart: { label: string; ts: number } | null = null
  let maxEnd: { label: string; ts: number } | null = null
  for (const rec of data.specialties) {
    const lbl = rec.dateRangeLabel
    if (!lbl) continue
    const parts = lbl.split(/\s*[–-]\s*/)
    const start = parts[0]?.trim()
    const end = (parts[1] ?? parts[0])?.trim()
    const sTs = start ? parseDate(start) : null
    const eTs = end ? parseDate(end) : null
    if (start && sTs !== null && (!minStart || sTs < minStart.ts)) minStart = { label: start, ts: sTs }
    if (end && eTs !== null && (!maxEnd || eTs > maxEnd.ts)) maxEnd = { label: end, ts: eTs }
  }
  const range =
    minStart && maxEnd && minStart.label !== maxEnd.label
      ? `${minStart.label} – ${maxEnd.label}`
      : (minStart ?? maxEnd)?.label ?? null

  // Build the sentence — minimal, no specialty list, no fluff. Keeps
  // the preamble readable on a single short line and lets the card
  // below do the heavy lifting.
  const opening = `Here's the cross-consultation brief for **${data.patientName}**.`
  const middleBits: string[] = []
  if (encounters > 0) {
    middleBits.push(
      `**${encounters} encounter${encounters === 1 ? "" : "s"}** across **${specialtyCount} specialt${specialtyCount === 1 ? "y" : "ies"}**`,
    )
  } else if (specialtyCount > 0) {
    middleBits.push(`**${specialtyCount} specialt${specialtyCount === 1 ? "y" : "ies"}**`)
  }
  middleBits.push(`over **${months} month${months === 1 ? "" : "s"}**`)
  if (range) middleBits.push(`(${range})`)
  let main = ""
  if (middleBits.length > 0) {
    main = ` ${middleBits.join(" ")}`
  }
  const doctorClause =
    doctorCount > 0 ? `, seen by **${doctorCount} doctor${doctorCount === 1 ? "" : "s"}**.` : "."
  return `${opening}${main}${doctorClause}`.replace(/\s+/g, " ").trim()
}

